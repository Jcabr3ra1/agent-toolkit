import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { createPeerReviewStore } from '../src/peer-review-store.js';
import { registerReviewer, deliverReview } from '../src/codex-delivery.js';
import { runPeerInboxCli } from '../src/peer-inbox-cli.js';
import { initializeMemory } from '../src/init.js';

test('journey: approved handoff, explicit notice, report, metrics, closure and recovery into a memory draft', async t => {
  const root=await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(),'toolkit-journey-')));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const projectRoot=path.join(root,'source'), storage=path.join(root,'store');
  await fs.mkdir(projectRoot,{mode:0o700}); await fs.writeFile(path.join(projectRoot,'answer.js'),'export const answer = 42;\n');
  execFileSync('git',['init','-b','main',projectRoot],{stdio:'ignore'});
  const vault=path.join(root,'memory');
  const init=initializeMemory({destination:vault,sourcePath:projectRoot,projectId:'journey',projectName:'Fictitious journey',syncMode:'none',apply:true});
  assert.equal(init.status,'created');
  const store=createPeerReviewStore({root:storage});
  const task=await store.startCollaboration({projectRoot,project:'Example',title:'Check answer',objective:'Confirm 42',primaryAgent:'claude',context:'Synthetic integration fixture, not a native AI session.'});
  const bound={taskId:task.id,projectRoot};
  const draft=await store.prepareReview({...bound,from:'claude',to:'codex',message:'Check the result',paths:['answer.js']});
  const review=await store.dispatchReview(draft,{previewId:'a'.repeat(32)});
  const registry=path.join(root,'reviewers'), thread='11111111-1111-4111-8111-111111111111';
  await registerReviewer({projectRoot,thread,directory:registry});
  let notices=0;
  await deliverReview({store,...bound,reviewId:review.id,directory:registry,run:async (id,message)=>{
    notices++;assert.equal(id,thread);assert.ok(message.includes(review.id));assert.ok(!message.includes('Check the result'));return `Queued message ${thread}`;
  }});
  const reviewer=createPeerReviewStore({root:storage});
  const claim=await reviewer.claimReview({...bound,reviewId:review.id,agent:'codex'});
  await reviewer.submitReview({...bound,reviewId:review.id,agent:'codex',claimToken:claim.claimToken,content:'The value is 42. No AI model was used in this fixture.'});
  await store.recordOutcome({...bound,reviewId:review.id,agent:'claude',verdict:'aprobado',findings:0,upheld:0,level:'normal'});
  await store.recordUsage({...bound,measurement:{id:'fixture-call',agent:'codex',phase:'review',model:'fictional',source:'manual',totalTokens:10}});
  const output=path.join(vault,'09-ARCHIVO','journey-draft.md');
  const args=['cierre','--project-root',projectRoot,'--task',task.id,'--salida',output];
  let stdout='';const io={store,out:s=>{stdout+=s;},err:()=>{}};
  assert.equal(await runPeerInboxCli(args,io),0);
  assert.equal(JSON.parse(stdout).closed,true);
  const fresh=createPeerReviewStore({root:storage});
  assert.equal((await fresh.getCollaboration(bound)).state,'closed');
  assert.equal((await fresh.consumption({projectRoot})).summary.counters.totalTokens.sum,10);
  const note=await fs.readFile(output,'utf8');assert.ok(note.includes('42'));assert.ok(!note.includes(claim.claimToken));
  assert.match(note,/borrador/iu);assert.match(note,/no acredita/iu);
  assert.equal(await runPeerInboxCli(args,io),1);assert.equal(await fs.readFile(output,'utf8'),note);
  assert.equal(notices,1);
});
